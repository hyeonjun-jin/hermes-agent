"""Optional Chromium smoke against the running MOCK UI; never run against real mode."""
from playwright.sync_api import sync_playwright, expect
import json
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1050})
    page.goto('http://127.0.0.1:8501',wait_until='networkidle')
    expect(page.get_by_text('현재 Mock 모드입니다.',exact=False)).to_be_visible(timeout=30000)
    box=page.get_by_placeholder('질문을 입력하세요')
    expect(box).to_be_visible(timeout=30000)
    expect(page.get_by_text('대화 사용자: Alice',exact=True)).to_be_visible(timeout=10000)
    page.get_by_role('button',name='새 대화',exact=True).click()
    expect(page.get_by_text('이전 대화에서 알려주신 코드는 R-42입니다.',exact=False)).to_have_count(0,timeout=10000)
    box=page.get_by_placeholder('질문을 입력하세요')
    box.fill('제 업무 코드는 R-42입니다. 기억해주세요.');box.press('Enter')
    expect(page.get_by_text('알려주신 내용을 이 대화에서 참고하겠습니다.',exact=False)).to_be_visible(timeout=30000)
    box=page.get_by_placeholder('질문을 입력하세요');box.fill('앞서 알려준 코드는 무엇인가요?');box.press('Enter')
    expect(page.get_by_text('이전 대화에서 알려주신 코드는 R-42입니다.',exact=False)).to_be_visible(timeout=30000)
    def choose(name):
        page.get_by_role('combobox').first.click()
        page.get_by_role('option',name=name,exact=True).click()
        expect(page.get_by_text('대화 사용자: '+name,exact=True)).to_be_visible(timeout=10000)
    choose('Bob')
    page.get_by_role('button',name='새 대화',exact=True).click()
    expect(page.get_by_text('안녕하세요. 사용자 프로젝트는 beacon입니다.',exact=False)).to_have_count(0,timeout=10000)
    box=page.get_by_placeholder('질문을 입력하세요');box.fill('프로젝트를 알려주세요.');box.press('Enter')
    expect(page.get_by_text('안녕하세요. 사용자 프로젝트는 beacon입니다.',exact=False)).to_be_visible(timeout=30000)
    expect(page.get_by_text('이전 대화에서 알려주신 코드는 R-42입니다.',exact=False)).to_have_count(0,timeout=10000)
    choose('Carol')
    page.get_by_role('button',name='새 대화',exact=True).click()
    expect(page.get_by_text('cedar: learning, 초보자 설명 필요.',exact=False)).to_have_count(0,timeout=10000)
    box=page.get_by_placeholder('질문을 입력하세요');box.fill('현재 프로젝트 계획을 조사 분석 검증해 주세요.');box.press('Enter')
    expect(page.get_by_text('cedar: learning, 초보자 설명 필요.',exact=False)).to_be_visible(timeout=60000)
    expect(page.get_by_text('참고 문서: doc-5',exact=False)).to_be_visible(timeout=10000)
    page.get_by_text('답변 피드백',exact=True).last.click()
    page.get_by_role('textbox',name='의견',exact=True).last.fill('브라우저에서 근거와 답변을 확인했습니다.')
    page.get_by_role('button',name='피드백 저장',exact=True).last.click()
    expect(page.get_by_text('피드백을 저장했습니다. 자동 학습에는 사용하지 않습니다.',exact=True)).to_be_visible(timeout=10000)
    page.screenshot(path='/tmp/persona-chat-browser.png',full_page=True)
    choose('Alice')
    expect(page.get_by_text('이전 대화에서 알려주신 코드는 R-42입니다.',exact=False)).to_be_visible(timeout=30000)
    page.reload(wait_until='networkidle')
    expect(page.get_by_placeholder('질문을 입력하세요')).to_be_visible(timeout=30000)
    expect(page.get_by_text('이전 대화에서 알려주신 코드는 R-42입니다.',exact=False)).to_be_visible(timeout=30000)
    print(json.dumps({'browser':'Chromium','mode':'mock','checks':['alice_multi_turn','bob_persona_table','carol_multi_agent_citations','user_isolation','feedback','history_reload'],'passed':True}))
    browser.close()
